# 2022년 4월 13일 취소되지 않은 흉부외과(CS) 진료 예약 내역
# 진료예약번호, 환자이름, 환자번호, 진료과코드, 의사이름, 진료예약일시
# APNT_NO,    PT_NAME, PT_NO,   MCDP_CD, DR_NAME,  APNT_YMD
# 진료예약일시를 기준으로 오름차순
# APNT_YMD

SELECT A.APNT_NO, P.PT_NAME, P.PT_NO, A.MCDP_CD, D.DR_NAME, A.APNT_YMD
FROM PATIENT P
JOIN APPOINTMENT A
    ON A.PT_NO = P.PT_NO
JOIN DOCTOR D
    ON A.MDDR_ID = D.DR_ID
WHERE DATE(A.APNT_YMD) = '2022-04-13' AND A.APNT_CNCL_YN = 'N' AND A.MCDP_CD = 'CS'
ORDER BY A.APNT_YMD